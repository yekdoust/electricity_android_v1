  const br=breakdown(prov,city,start,end);if(br.zones.length){const scores={};for(const z of br.zones)scores[z]=0;for(let o=ord(...start);o<ord(...end);o++)for(const z of zoneSet(prov,city,o))scores[z]++;return +Object.keys(scores).sort((a,b)=>scores[b]-scores[a]||a-b)[0];}
