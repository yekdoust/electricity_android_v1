function fa(x){return Number(x).toLocaleString('fa-IR',{maximumFractionDigits:2});}
function norm(s){return String(s).replace(/[۰-۹]/g,d=>String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d))).replace(/[٠-٩]/g,d=>String('٠١٢٣٤٥٦٧٨٩'.indexOf(d))).replace(/[,،]/g,'').trim();}
function parseDate(s){
  const p=norm(s).replace(/[.\\-]/g,'/').split('/').filter(Boolean); if(p.length!==3) throw new Error('تاریخ باید مانند 1405/05/03 باشد');
  let a=+p[0],b=+p[1],c=+p[2],y,m,d; if(a===1405){y=a;m=b;d=c}else if(c===1405){y=c;m=b;d=a}else throw new Error('سال باید 1405 باشد');
  if(m<1||m>12) throw new Error('ماه نامعتبر است'); const md=m<=6?31:(m<=11?30:29); if(d<1||d>md) throw new Error('روز نامعتبر است'); return [m,d];
}
function ord(m,d){return m<=6?(m-1)*31+d:186+(m-7)*30+d;}
function fmt(o){let m,d;if(o<=186){m=Math.floor((o-1)/31)+1;d=(o-1)%31+1}else{const z=o-187;m=7+Math.floor(z/30);d=z%30+1}return `1405/${String(m).padStart(2,'0')}/${String(d).padStart(2,'0')}`;}
function span(a,b){const x=ord(...a),y=ord(...b); if(y<=x)throw new Error('تاریخ پایان باید بعد از تاریخ شروع باشد'); return y-x;}
function zoneSet(prov,city,o){const out=new Set();for(const [p,c,z,periods] of DATA.RULES){if(p!==prov)continue;if(c!==null && !c.includes(city))continue;for(const q of periods){const s=ord(q[0],q[1]),e=ord(q[2],q[3])+1;if(s<=o&&o<e)out.add(z)}}return [...out];}
function breakdown(prov,city,start,end){
  const a=ord(...start),b=ord(...end),total=b-a;let hot=0,cold=0;const zones=new Set();const seg=[];let cur=null;
  for(let o=a;o<b;o++){
    const zs=zoneSet(prov,city,o).sort((x,y)=>x-y), label=zs.length?'گرم':'سرد/غیرگرم';zs.forEach(z=>zones.add(z));
    if(!cur||cur.label!==label||JSON.stringify(cur.zones)!==JSON.stringify(zs)){if(cur)cur.days=o-cur.startOrd;cur={label,startOrd:o,zones:zs}};
    if(label==='گرم')hot++;else cold++;
  }
  if(cur){cur.days=b-cur.startOrd;cur.start=fmt(cur.startOrd);cur.end=fmt(b);seg.push(cur)};
  // rebuild segments correctly
  const groups=[];let last=null;for(let o=a;o<b;o++){const zs=zoneSet(prov,city,o).sort((x,y)=>x-y), label=zs.length?'گرم':'سرد/غیرگرم';
    const key=label+'|'+zs.join(',');if(!last||last.key!==key){if(last){last.days=o-last.startOrd;last.end=fmt(o);groups.push(last)};last={key,label,startOrd:o,start:fmt(o),zones:zs}}
  }
  if(last){last.days=b-last.startOrd;last.end=fmt(b);groups.push(last)}
  return {total,hot,cold,hotPct:100*hot/total,coldPct:100*cold/total,zones:[...zones].sort((x,y)=>x-y),segments:groups};
}
