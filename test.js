  const start=parseDate(document.getElementById('start').value), end=parseDate(document.getElementById('end').value), days=span(start,end),kwh=curr-prev,monthly=kwh*30/days;
  const prov=document.getElementById('province').value,city=document.getElementById('city').value,br=breakdown(prov,city,start,end),zone=chooseZone(prov,city,start,end)||1;
  const [hotCoef,coldCoef]=DATA.ZONE_COEFF[zone];const weighted=br.hot*hotCoef+br.cold*coldCoef;const mode=br.hot===days?'گرم':(br.cold===days?'سرد/غیرگرم':'ترکیبی');
  const hotKwh=kwh*(br.hot/days),coldKwh=kwh*(br.cold/days);let rows=[],monthEnergy=0,periodEnergy=0,method='',split=[];
  if(mode!=='ترکیبی'){const [table,m]=tariff(zone,monthly,mode);const ap=applyTable(monthly,table);rows=ap.rows;monthEnergy=ap.total;periodEnergy=monthEnergy*days/30;method=m;}
